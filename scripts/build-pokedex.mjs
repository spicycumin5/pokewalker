// One-time build step: fetches Gen 1–4 species from PokéAPI and bundles
// HGSS front sprites so the app never calls PokéAPI at runtime.
//
//   node scripts/build-pokedex.mjs
//
// Outputs:
//   src/data/pokedex.json   species data
//   src/data/sprites.ts     static require() map (Metro needs literal paths)
//   assets/sprites/<id>.png   LCD-palette sprites (raw copies cached in scripts/.sprite-cache)

import { mkdir, writeFile, access } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const MAX_ID = 493;
const CONCURRENCY = 8;
const SPRITE_SCALE = 4;
const API = 'https://pokeapi.co/api/v2';
const root = path.resolve(import.meta.dirname, '..');
const spriteDir = path.join(root, 'assets', 'sprites');
const cacheDir = path.join(root, 'scripts', '.sprite-cache');

// Must match LCD in src/ui/theme.ts, darkest to lightest.
const PALETTE = [
  [0x1e, 0x2a, 0x1e],
  [0x4a, 0x5d, 0x43],
  [0x8a, 0x9a, 0x73],
  [0xc9, 0xd3, 0xb0],
];

/** Maps each opaque pixel's luminance onto the 4-shade LCD palette. */
async function lcdify(src, dest) {
  const { data, info } = await sharp(src).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  let min = 255;
  let max = 0;
  const lum = new Float32Array(info.width * info.height);
  for (let i = 0; i < lum.length; i++) {
    const o = i * 4;
    lum[i] = 0.299 * data[o] + 0.587 * data[o + 1] + 0.114 * data[o + 2];
    if (data[o + 3] > 127) {
      min = Math.min(min, lum[i]);
      max = Math.max(max, lum[i]);
    }
  }
  const range = Math.max(1, max - min);
  for (let i = 0; i < lum.length; i++) {
    const o = i * 4;
    if (data[o + 3] <= 127) {
      data[o + 3] = 0;
      continue;
    }
    const shade = Math.min(3, Math.floor(((lum[i] - min) / range) * 4));
    [data[o], data[o + 1], data[o + 2]] = PALETTE[shade];
    data[o + 3] = 255;
  }
  // Pre-scale with nearest-neighbour so on-device downscaling stays crisp.
  await sharp(data, { raw: info })
    .resize(info.width * SPRITE_SCALE, info.height * SPRITE_SCALE, { kernel: 'nearest' })
    .png({ palette: true })
    .toFile(dest);
}

async function getJson(url, tries = 3) {
  for (let i = 0; ; i++) {
    try {
      const res = await fetch(url);
      if (!res.ok) throw new Error(`${res.status} ${url}`);
      return await res.json();
    } catch (err) {
      if (i >= tries - 1) throw err;
      await new Promise((r) => setTimeout(r, 1000 * (i + 1)));
    }
  }
}

async function exists(p) {
  try {
    await access(p);
    return true;
  } catch {
    return false;
  }
}

async function buildOne(id) {
  const [mon, species] = await Promise.all([
    getJson(`${API}/pokemon/${id}`),
    getJson(`${API}/pokemon-species/${id}`),
  ]);

  const gen4 = mon.sprites.versions?.['generation-iv'];
  const spriteUrl =
    gen4?.['heartgold-soulsilver']?.front_default ??
    gen4?.platinum?.front_default ??
    mon.sprites.front_default;

  const rawPath = path.join(cacheDir, `${id}.png`);
  if (spriteUrl && !(await exists(rawPath))) {
    const res = await fetch(spriteUrl);
    if (!res.ok) throw new Error(`sprite ${res.status} ${spriteUrl}`);
    await writeFile(rawPath, Buffer.from(await res.arrayBuffer()));
  }
  await lcdify(rawPath, path.join(spriteDir, `${id}.png`));

  const englishName =
    species.names.find((n) => n.language.name === 'en')?.name ?? mon.name;

  return {
    id,
    name: englishName,
    types: mon.types.sort((a, b) => a.slot - b.slot).map((t) => t.type.name),
    captureRate: species.capture_rate,
    legendary: species.is_legendary || species.is_mythical,
    baby: species.is_baby,
  };
}

async function main() {
  await mkdir(spriteDir, { recursive: true });
  await mkdir(cacheDir, { recursive: true });
  const ids = Array.from({ length: MAX_ID }, (_, i) => i + 1);
  const results = new Array(MAX_ID);
  let next = 0;
  let done = 0;

  await Promise.all(
    Array.from({ length: CONCURRENCY }, async () => {
      while (next < ids.length) {
        const idx = next++;
        results[idx] = await buildOne(ids[idx]);
        if (++done % 50 === 0) console.log(`${done}/${MAX_ID}`);
      }
    }),
  );

  await writeFile(
    path.join(root, 'src', 'data', 'pokedex.json'),
    JSON.stringify(results),
  );

  const lines = results.map(
    (s) => `  ${s.id}: require('@/assets/sprites/${s.id}.png'),`,
  );
  await writeFile(
    path.join(root, 'src', 'data', 'sprites.ts'),
    `// Generated by scripts/build-pokedex.mjs — do not edit.\n` +
      `// Values are Metro asset ids, accepted by expo-image's source prop.\n\n` +
      `export const sprites: Record<number, number> = {\n` +
      `${lines.join('\n')}\n};\n`,
  );

  console.log(`Wrote ${results.length} species.`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
